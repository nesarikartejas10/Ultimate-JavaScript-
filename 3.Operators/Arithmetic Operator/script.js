//binary operators
let a = 4;
let b = 2;

console.log(a + b); //6
console.log(a - b); //2
console.log(a * b); //8
console.log(a / b); //2
console.log(a % b); //0
console.log(a ** b); //16

//unary operators

let x = 10;
let y = 20;

console.log(++x); //11
console.log(x++); //11
console.log(--y); //19
console.log(y--); //19
